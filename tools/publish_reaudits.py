def do_serious_sam(games):
    fr = next(f for f in games if f.get("franchise_slug") == "serious-sam")
    have = {e["title"] for e in fr["entries"]}
    added = [e for e in SS_NEW if e["title"] not in have]
    fr["entries"].extend(added)
    for e in fr["entries"]:
        if e["title"] in SS_REVISED:
            e.update(SS_REVISED[e["title"]])
        if e["title"] == "Serious Sam HD: The Second Encounter":
            c = (e.get("remaster_caveats") or "").rstrip()
            extra = ("Its add-on campaign belongs to this entry and must be installed with it: "
                     "three extra levels plus additional versus and survival maps.")
            if extra not in c:
                e["remaster_caveats"] = (c + " " + extra).strip()
    fr["entries"].sort(key=lambda e: (e["release_year"], e["title"]))
    fr["summary"] = ("Croteam's arena shooter series, played in release order with every version of "
                     "a title kept together — including the virtual reality rebuilds, the licensed "
                     "spin-offs, and the handheld and console releases that are usually left out.")
    return len(added), len(fr["entries"])


