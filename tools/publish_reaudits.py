def do_fromsoftware(games):
    rows = json.loads(FS_SRC.read_text(encoding="utf-8"))
    rows.sort(key=lambda r: (r["year"], r.get("date", ""), r["en"]))
    entries = []
    for r in rows:
        gdec = r.get("group_decision")
        role = DECISION.get(gdec, "")
        if not role and r.get("kind") == "tool":
            role = ("A creation tool rather than a game, listed because it is part of what the "
                    "studio released.")
        entries.append({
            "title": r["en"], "release_year": r["year"],
            "sami": {"chosen_platform": r.get("platform", ""), "rating": "", "difficulty": "",
                     "completion_date": "", "notes": ""},
            "definitive_edition": "", "emulation": public(r.get("widescreen_route")),
            "status": public(r.get("availability")) or r.get("availability", "").lstrip("✅ "),
            "primary": r.get("platform", ""), "secondary": "",
            "remaster_caveats": (FS_OVERRIDE.get(r["en"])
                                 or public(r.get("group_why") or r.get("note"))
                                 # ⭐ never leave an entry blank — say plainly that it had one
                                 # release, which is itself the answer to "which version?"
                                 or "Released once, in a single version, so there is no edition "
                                    "question to settle — this is the only way it exists."),
            "version_groups": ([r["version_group"]] if r.get("version_group") else []),
            "version_role": role, "all_releases": [], "confidence": "researched",
            "fidelity_vs_completeness_conflict": "",
        })
    rec = {
        "franchise": "FromSoftware", "franchise_slug": "fromsoftware", "era": "1994 – present",
        "summary": ("Everything the studio has made, not only the Souls games — 129 releases across "
                    "three decades, taking in the mech series, the first-person dungeon crawlers, "
                    "the ninja games, licensed mecha work, puzzle and sudoku titles, handheld and "
                    "phone releases, one virtual reality game and one arcade machine. Versions of "
                    "the same title are kept together, and each entry says which other releases "
                    "are required and why."),
        "entries": entries,
    }
    games[:] = [f for f in games if f.get("franchise_slug") != "fromsoftware"]
    games.append(rec)
    return len(entries)


HARDWARE = re.compile(r"\b(RTX|GTX|Radeon|Ryzen|Core i[3579]|NVIDIA|GeForce|AMD|Intel|"
                      r"PG32UCDM|4090|5090)\b", re.I)


def audit_public_text(games):
    """⛔ Refuse to write if internal notes, source names or hardware reached a published record."""
    bad = []
    for fr in games:
        if fr.get("franchise_slug") not in ("serious-sam", "fromsoftware"):
            continue
        for e in fr.get("entries") or []:
            for field in ("remaster_caveats", "version_role", "emulation", "status",
                          "definitive_edition"):
                v = e.get(field) or ""
                if BANNED.search(v):
                    bad.append(f"{e['title']} / {field}: source or internal language")
                if HARDWARE.search(v):
                    bad.append(f"{e['title']} / {field}: hardware identity")
                if MARKERS.search(v):
                    bad.append(f"{e['title']} / {field}: working-note markers")
    return bad


def main():
    games = json.loads(GAMES.read_text(encoding="utf-8"))
    added, total = do_serious_sam(games)
    n = do_fromsoftware(games)

    problems = audit_public_text(games)
    if problems:
        print(f"  ⛔ REFUSING TO WRITE — {len(problems)} problem(s) in public text:")
        for p in problems[:20]:
            print(f"      {p}")
        return 1
    print("  ✅ public text clean: no source names, no internal markers, no hardware")

    games.sort(key=lambda f: (f.get("franchise") or "").lower())
    GAMES.write_text(json.dumps(games, ensure_ascii=False, indent=1),
                     encoding="utf-8", newline="\n")
    print(f"  Serious Sam: +{added} entries -> {total}")
    print(f"  FromSoftware: {n} entries added as a new record")
    print(f"  games.json now holds {len(games)} franchises")
    print("  ⇒ now run: python tools/build_game_index.py")


if __name__ == "__main__":
    raise SystemExit(main())
