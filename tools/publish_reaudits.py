# \u26d4\u26d4 The audit files are MY WORKING NOTES. They carry priority markers, references to who said
# what, and \u2014 the part that actually matters \u2014 the NAMES OF SOURCES. We never cite a source, so a
# source name must never reach a page. This converts a working note into public prose, and main()
# refuses to write if anything slips through.
BANNED = re.compile(
    r"wikipedia|giant\s*bomb|gundam\s*wiki|mobygames|fandom|steam\s*community|"
    r"gg\.deals|codex|category sweep|2026-\d\d-\d\d|his rules?|his ruling|he said|"
    r"researched|according to|source", re.I)
MARKERS = re.compile(r"[\u2b50\u26d4\u26a0\u2705\u23f0\ufe0f]+\s*")


# Real acronyms and proper nouns keep their case; my SHOUTED emphasis does not.
KEEP_CASE = {"PS1", "PS2", "PS3", "PS4", "PS5", "PSP", "PSVR", "DS", "3DS", "PC", "VR", "HD",
             "HDR", "DLC", "XBLA", "GOTY", "RPG", "JRPG", "NPC", "AI", "UI", "FPS", "KF1"}
PROPER = {"JAPAN": "Japan", "JAPAN-ONLY": "Japan-only", "STEAM": "Steam", "SWITCH": "Switch",
          "SIXAXIS": "Sixaxis", "WESTERN": "Western", "AMERICAN": "American",
          "NORTH": "North", "AMERICA": "America", "PORTABLE": "Portable"}


def deshout(text):
    """Undo the ALL-CAPS emphasis I use in working notes \u2014 it reads as shouting on a page."""
    def fix(m):
        w = m.group(0)
        if w in KEEP_CASE:
            return w
        if w in PROPER:
            return PROPER[w]
        base = w.split("-")[0]
        if base in PROPER:
            return PROPER[base] + w[len(base):].lower()
        return w.lower()
    return re.sub(r"\b[A-Z][A-Z0-9'-]{2,}\b", fix, text)


def public(text):
    """Turn an internal audit note into neutral prose fit for the site."""
    if not text:
        return ""
    text = MARKERS.sub("", str(text)).replace("HIS RULING:", "").strip()
    # keep only sentences that carry no internal or source language
    parts = re.split(r"(?<=[.!?])\s+", text)
    keep = [p.strip() for p in parts if p.strip() and not BANNED.search(p)]
    out = deshout(" ".join(keep))
    out = re.sub(r"\s{2,}", " ", out).strip(" -\u2014")
    # a note that was ENTIRELY internal leaves nothing behind - better empty than leaking
    if len(out) <= 25:
        return ""
    return out[0].upper() + out[1:]


def entry(title, year, platform, role, caveat, groups=(), status="Not yet acquired",
          definitive="", emulation=""):
    return {
        "title": title, "release_year": year,
        "sami": {"chosen_platform": platform, "rating": "", "difficulty": "",
                 "completion_date": "", "notes": ""},
        "definitive_edition": definitive, "emulation": emulation, "status": status,
        "primary": platform, "secondary": "", "remaster_caveats": caveat,
        "version_groups": list(groups), "version_role": role,
        "all_releases": [], "confidence": "researched",
        "fidelity_vs_completeness_conflict": "",
    }


